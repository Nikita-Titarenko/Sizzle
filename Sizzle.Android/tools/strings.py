# Not translated: identifiers and names shown in their own language.
UNTRANSLATABLE = {"app_name", "notification_channel_new_recipes_id"}


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    return text if not text.startswith(("@", "?")) else "\\" + text


def write(path: str, column: int) -> None:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tools/strings.py. Edit the table there, not this file. -->",
             "<resources>"]
    for row in S:
        key = row[0]
        if column == 2 and key in UNTRANSLATABLE:
            continue
        attrs = ' translatable="false"' if key in UNTRANSLATABLE else ""
        lines.append(f'    <string name="{key}"{attrs}>{escape(row[column])}</string>')
    lines.append("</resources>\n")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


