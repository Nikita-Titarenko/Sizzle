import { IngredientUnit } from './catalog.model';

export interface Recipe {
  id: string;
  userId: string;
  userName: string;
  userImageUrl: string | null;
  name: string;
  description: string;
  cookingTimeMinutes: number;
  categoryId: string;
  fileUrl: string | null;
  viewCount: number;
  likeCount: number;
  creationDate: string;
  isDraft?: boolean;
  isAIGeneratedImage?: boolean;
  /** Sum of the ingredients' calories; 0 when the catalog has no calories for them. */
  calories?: number;
}

export interface FeedRecipe extends Recipe {
  isFollowed: boolean;
  isLiked: boolean;
  isSaved: boolean;
}

export interface RecipeStep {
  id: string;
  name: string;
  description: string;
  fileUrls: string[];
}

export interface RecipeIngredient {
  id: string;
  name: string;
  quantity: number;
  unit: string;
}

export interface RecipeDetails extends FeedRecipe {
  steps: RecipeStep[];
  ingredients: RecipeIngredient[];
}

export interface RecipeLike {
  recipeId: string;
  isLiked: boolean;
}

export interface RecipeSave {
  recipeId: string;
  isSaved: boolean;
}

export interface RecipeQuery {
  search?: string;
  categoryIds?: string[];
  ingredientIds?: string[];
  userId?: string;
  pageIndex?: number;
  pageSize?: number;
}

export interface RecipeFormValue {
  isDraft: boolean;
  /** Whether `file` was generated by AI; the API ignores it when no new file is sent. */
  isAIGeneratedImage: boolean;
  name: string;
  description: string;
  cookingTimeMinutes: number;
  categoryId: string;
  file: File | null;
  steps: { name: string; description: string; files: File[] }[];
  ingredients: { id: string; quantity: number }[];
  newIngredients: {
    name: string;
    parentId: string | null;
    unit: IngredientUnit;
    quantity: number;
  }[];
}

/**
 * A recipe as the AI reads and writes it (recipes/generate, generate-from-video,
 * generate-image and the reviewer's correctedRecipe). Ingredients without an id are new.
 */
export interface GeneratedRecipe {
  name: string;
  description: string;
  cookingTimeMinutes: number;
  categoryId: string;
  steps: { name: string; description: string }[];
  ingredients: GeneratedIngredient[];
}

export interface GeneratedIngredient {
  id: string | null;
  name: string;
  parentId: string | null;
  unit: IngredientUnit;
  quantity: number;
}

/** One server-sent event from a generation stream. */
export type GenerationEvent =
  | { type: 'chunk'; text: string }
  | { type: 'completed'; result: { recipe: GeneratedRecipe; message: string } }
  | { type: 'error'; errors: { message: string; key?: number | string }[] };

export interface IngredientProportion {
  id: string;
  quantity: number;
}
